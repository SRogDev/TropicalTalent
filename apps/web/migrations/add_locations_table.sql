-- Create locations table
CREATE TABLE IF NOT EXISTS public.locations (
    -- ID INTERNO (Primary Key): Único en TU base de datos
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- ID de Google (Clave Única Externa): Es el 'place_id' de la API
    google_place_id TEXT UNIQUE NOT NULL,

    -- Datos Geográficos (Nombres semánticos)
    city TEXT,               -- La 'locality' (Ej: 'Cambridge', 'Houston')
    county TEXT,             -- 'administrative_area_level_2' (Ej: 'West Sussex', 'Harris County')
    country TEXT,            -- El país (Ej: 'United Kingdom', 'United States')

    -- Auditoría
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- ÍNDICE COMPUESTO para búsquedas rápidas por ciudad y condado
CREATE INDEX IF NOT EXISTS idx_locations_city_county ON public.locations (city, county);

-- ÍNDICE para búsquedas por google_place_id
CREATE INDEX IF NOT EXISTS idx_locations_google_place_id ON public.locations (google_place_id);

-- Migrate existing location data
-- This will parse existing "City, County" format and create location records
-- Note: This is a best-effort migration for existing data
DO $$
DECLARE
    user_record RECORD;
    location_parts TEXT[];
    city_val TEXT;
    county_val TEXT;
    v_location_id BIGINT;
BEGIN
    FOR user_record IN
        SELECT id, location
        FROM public.users
        WHERE location IS NOT NULL
        AND location != ''
        AND location::TEXT NOT SIMILAR TO '[0-9]+' -- Skip if already migrated to ID
    LOOP
        -- Split location by comma
        location_parts := string_to_array(user_record.location, ',');

        IF array_length(location_parts, 1) >= 2 THEN
            city_val := trim(location_parts[1]);
            county_val := trim(location_parts[2]);

            -- Insert or get existing location
            INSERT INTO public.locations (google_place_id, city, county, country)
            VALUES (
                'migrated_' || user_record.id, -- Temporary placeholder for migrated data
                city_val,
                county_val,
                NULL -- No country data from old format
            )
            ON CONFLICT (google_place_id) DO NOTHING
            RETURNING id INTO v_location_id;

            -- If ON CONFLICT happened, get the existing ID
            IF v_location_id IS NULL THEN
                SELECT id INTO v_location_id
                FROM public.locations
                WHERE google_place_id = 'migrated_' || user_record.id;
            END IF;

            -- Update user with location_id temporarily in a new column
            -- We'll do the actual column change after this
        END IF;
    END LOOP;
END $$;

-- Add new column for location_id (temporary)
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS location_id BIGINT;

-- Migrate data from old location to location_id
DO $$
DECLARE
    user_record RECORD;
    location_parts TEXT[];
    city_val TEXT;
    county_val TEXT;
    v_location_id BIGINT;
BEGIN
    FOR user_record IN
        SELECT id, location
        FROM public.users
        WHERE location IS NOT NULL
        AND location != ''
        AND location::TEXT NOT SIMILAR TO '[0-9]+' -- Skip if already migrated to ID
    LOOP
        -- Get the location_id we created earlier
        SELECT l.id INTO v_location_id
        FROM public.locations l
        WHERE l.google_place_id = 'migrated_' || user_record.id;

        IF v_location_id IS NOT NULL THEN
            UPDATE public.users
            SET location_id = v_location_id
            WHERE id = user_record.id;
        END IF;
    END LOOP;
END $$;

-- Drop the old location column
ALTER TABLE public.users DROP COLUMN IF EXISTS location;

-- Rename location_id to location
ALTER TABLE public.users RENAME COLUMN location_id TO location;

-- Add foreign key constraint
ALTER TABLE public.users
ADD CONSTRAINT fk_users_location
FOREIGN KEY (location)
REFERENCES public.locations(id)
ON DELETE SET NULL;

-- Enable Row Level Security on locations table
ALTER TABLE public.locations ENABLE ROW LEVEL SECURITY;

-- Policy: Anyone can read locations
CREATE POLICY "Locations are viewable by everyone"
ON public.locations
FOR SELECT
USING (true);

-- Policy: Only authenticated users can insert locations
CREATE POLICY "Authenticated users can insert locations"
ON public.locations
FOR INSERT
TO authenticated
WITH CHECK (true);
